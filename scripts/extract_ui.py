def load_exe(path):
    with open(path, "rb") as f:
        return f.read()


def get_entries(data, start, end):
    out = []
    i = start
    while i < end:
        nul = data.find(b"\x00", i)
        if nul == -1 or nul >= end:
            break
        raw = data[i:nul]
        out.append((i, raw.decode("utf-8", errors="replace")))
        i = nul + 1
    return out


def main():
    os.makedirs(os.path.dirname(OUT_TSV), exist_ok=True)
    data = load_exe(BACKUP)
    entries = get_entries(data, TABLE_START, TABLE_END)
    jp = entries[2657:3019]

    rows = []
    for i, (jp_off, jp_text) in enumerate(jp):
        if i + 1 < len(jp):
            next_off = jp[i + 1][0]
        else:
            next_off = TABLE_END
        max_bytes = next_off - jp_off - 1

        en_text = JP2EN.get(jp_text, "")
        rows.append((jp_off, en_text, jp_text, max_bytes))

    with open(OUT_TSV, "w", encoding="utf-8") as f:
        f.write("jp_offset\tenglish\tjapanese_original\tkorean\tmax_bytes\n")
        for r in rows:
            f.write(f"{r[0]}\t{r[1]}\t{r[2]}\t\t{r[3]}\n")

    mapped = sum(1 for r in rows if r[1])
    unmapped = sum(1 for r in rows if not r[1])
    print(f"Total: {len(rows)} rows (mapped={mapped}, unmapped={unmapped})")


if __name__ == "__main__":
    main()